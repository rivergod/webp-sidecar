def md_cell(text: str) -> str:
    """표 셀 안의 '|'와 줄바꿈을 이스케이프한다."""
    return text.replace("\\", "\\\\").replace("|", "\\|").replace("\n", " ")


def code(text: str) -> str:
    return "`" + text.replace("`", "'") + "`"


def origin_text(e: dict) -> str:
    o = e["origin"]
    if o["type"] == "download":
        short = o["commit"][:7]
        return f"[Compact-ICC-Profiles@{short}]({o['url']}) {code(o['repo_path'])}"
    if o["type"] == "tampered":
        return f"변조(`scripts/tamper.py`), 시드 {code(o['seed'])}: {o['change']}"
    cmds = o.get("commands", [])
    parts = ["자체 생성(`scripts/generate.py`)"]
    if o.get("step"):
        parts.append(o["step"])
    if cmds:
        last = cmds[-1]
        more = f" 외 {len(cmds) - 1}개" if len(cmds) > 1 else ""
        parts.append(f"{code(last)}{more}")
    return ": ".join([parts[0], ", ".join(parts[1:])]) if len(parts) > 1 else parts[0]


def notes_text(e: dict) -> str:
    bits = []
    exp = e.get("expected", {})
    if e["origin"]["type"] == "tampered":
        obs = exp["observed"]
        if exp["decoder"] == "still":
            tool, detail = "dwebp", obs["dwebp"].get("message", "")
            m = re.search(r"Status: \d+\((\w+)\)", detail)
            detail = m.group(1) if m else ""
        else:
            tool, detail = "WebPAnimDecoder", obs["anim_decoder"].get("stage", "")
        result = f"{exp['kind']}; {tool} {exp['outcome']}"
        if exp["outcome"] == "reject" and detail:
            result += f" ({detail})"
        if exp["decoder"] == "still" and exp["outcome"] == "accept" and not obs["demux"].get("ok"):
            result += ", WebPDemux reject"
        bits.append(result)
        if "outcome_with_8gib" in exp:
            bits.append(f"8 GiB 상한에서 {exp['outcome_with_8gib']}")
        if exp.get("exceeds_default_limits"):
            bits.append("서버 기본 상한 초과: " + ", ".join(exp["exceeds_default_limits"]))
    elif e.get("notes"):
        bits.append(e["notes"])
    if "features" in exp:
        f = exp["features"]
        if f["has_animation"]:
            bits.append(f"{f['width']}x{f['height']} anim, {exp['animation']['frame_count']} frames")
        else:
            bits.append(f"{f['width']}x{f['height']} {f['format']}" + (" alpha" if f["has_alpha"] else ""))
    return md_cell("; ".join(bits))


def render_sources(manifest: dict) -> str:
    lines = [
        "# 샘플 출처와 라이선스",
        "",
        "이 파일은 `manifest.json`에서 `python3 -I samples/scripts/manifest.py`로 생성한다. 직접 고치지 않는다.",
        "명령 전체, 기대값(RGBA8 SHA-256, 메타데이터 해시, 손상 입력 판정)은 `manifest.json`에 있다.",
        "",
        "| 경로 | 출처 | 라이선스 | SHA-256 | 비고 |",
        "|---|---|---|---|---|",
    ]
    for e in manifest["files"]:
        lines.append("| " + " | ".join([
            code(e["path"]), md_cell(origin_text(e)), e["license"], code(e["sha256"]), notes_text(e),
        ]) + " |")
    lines += [
        "",
        "## 커밋하지 않는 세트",
        "",
        "| 위치 | 출처 | 라이선스 | 고정 | 받는 방법 | 비고 |",
        "|---|---|---|---|---|---|",
    ]
    for x in manifest["external"]:
        pin = x.get("pin") or (f"커밋 {code(x['commit'])}, 파일별 sha256: {code(x['lock'])}" if "commit" in x
                               else "결정적 생성(고정 시드)")
        src = f"[{x['name']}]({x['url']})" if "url" in x else x["name"]
        lines.append("| " + " | ".join([
            code(x["dest"]), src, md_cell(x["license"]), pin, code(x["fetch"]), md_cell(x["notes"]),
        ]) + " |")
    return "\n".join(lines) + "\n"


