def build() -> dict:
    generated = sl.read_records("generated")
    malformed = sl.read_records("malformed")
    expected = {e["path"]: e["expected"] for e in sl.read_records("expected")}
    files = []
    for r in generated + malformed:
        entry = dict(r)
        entry.pop("source_rgba", None)  # PNG 기대값은 expected.decode로 옮겨졌다
        if r["path"] in expected:
            entry["expected"] = expected[r["path"]]
        path = sl.SAMPLES_DIR / r["path"]
        entry["sha256"] = sl.sha256_file(path)
        entry["size"] = path.stat().st_size
        files.append(entry)
    files.sort(key=lambda e: e["path"])
    manifest = header()
    manifest["files"] = files
    return manifest


