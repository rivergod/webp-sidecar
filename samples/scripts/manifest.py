def committed_files() -> list[Path]:
    """samples/ 아래 커밋 대상 파일(무시 디렉터리 제외)."""
    out = []
    for p in sorted(sl.SAMPLES_DIR.rglob("*")):
        parts = p.relative_to(sl.SAMPLES_DIR).parts
        if any(part in IGNORED_DIRS for part in parts) or not p.is_file():
            continue
        out.append(p)
    return out


def check() -> int:
    errors = []
    with open(MANIFEST, encoding="utf-8") as f:
        manifest = json.load(f)
    listed = set()
    for e in manifest["files"]:
        path = sl.SAMPLES_DIR / e["path"]
        listed.add(e["path"])
        if not path.is_file():
            errors.append(f"missing file: {e['path']}")
            continue
        if path.is_symlink():
            errors.append(f"symlink not allowed: {e['path']}")
        if path.stat().st_size != e["size"] or sl.sha256_file(path) != e["sha256"]:
            errors.append(f"sha256/size mismatch: {e['path']}")
        if e["size"] > sl.MAX_FILE_BYTES:
            errors.append(f"file larger than {sl.MAX_FILE_BYTES} bytes: {e['path']}")
        if e["license"] not in ALLOWED_LICENSES:
            errors.append(f"license not allowed: {e['path']} ({e['license']})")
    for d in TRACKED_DIRS:
        for p in sorted((sl.SAMPLES_DIR / d).rglob("*")):
            if p.is_file() and sl.rel(p) not in listed:
                errors.append(f"file not in manifest: {sl.rel(p)}")
    total = sum(p.stat().st_size for p in committed_files())
    if total > sl.MAX_TOTAL_BYTES:
        errors.append(f"samples/ total {total} bytes exceeds {sl.MAX_TOTAL_BYTES}")
    if not SOURCES.exists() or SOURCES.read_text(encoding="utf-8") != render_sources(manifest):
        errors.append("SOURCES.md is not up to date with manifest.json")
    for msg in errors:
        print(f"ERROR: {msg}", file=sys.stderr)
    print(f"manifest check: {len(manifest['files'])} files, committed total {total} bytes, "
          f"{len(errors)} error(s)")
    return 1 if errors else 0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify committed files only")
    args = ap.parse_args()
    if args.check:
        sys.exit(check())
    manifest = build()
    sl.write_text(MANIFEST, sl.dump_json(manifest))
    sl.write_text(SOURCES, render_sources(manifest))
    print(f"manifest: {len(manifest['files'])} files -> {sl.rel(MANIFEST)}, {sl.rel(SOURCES)}")


if __name__ == "__main__":
    main()
